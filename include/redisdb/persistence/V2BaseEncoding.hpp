#pragma once
#include "redisdb/persistence/V2BaseStream.hpp"
#include <optional>
#include <span>
#include <string>
#include <string_view>
#include <vector>

namespace redisdb::persistence::v2 {
// Caller keeps all entry/key/index storage alive and immutable through cursor lifetime.
struct BaseEntryView final {
    std::string_view key;
    const storage::Entry* entry; // non-null; borrowed stable physical entry
};
struct BaseInputView final {
    std::span<const BaseEntryView> entries; // strict unsigned-byte key order
    bool include_lru;
    std::span<const std::size_t> lru_indices; // oldest first; exact permutation if enabled
};
struct BaseEncodingContext final {
    StoreId store;
    GenerationId selected_generation;
    GenerationId candidate_generation;
    LogicalSequence captured_sequence;
    SourceTuple synchronized_source; // caller-attested P0 coordinates, not authenticated
};
// Every budget is explicit. Policy charge and requested buffers are NOT RSS.
struct BaseEncodeLimits final {
    std::size_t max_entries;
    std::uint64_t max_bytes;           // 204..MaxFileBytes, may exceed 64 MiB
    std::size_t max_frame_payload;     // 4..MaxKeyPayload; also bounds LRU payload
    std::size_t max_permutation_bytes; // ceil(K/8) bitmap when LRU is enabled
    std::size_t max_logical_charge;
};
enum class BaseEncodeError {
    None,
    Closed,
    InvalidContext,
    InvalidInput,
    KeyOrder,
    Permutation,
    EntryEncoding,
    ChargeOverflow,
    ExtentOverflow,
    ResourceLimit
};
struct BaseEncodeFailure final {
    BaseEncodeError code = BaseEncodeError::None;
    std::optional<Error> fixed_format;
    std::optional<BaseStreamError> frame_format;
};
enum class BaseEncodeStep { Chunk, End, Error };
class BaseEncodingCursor;
class EncodedBaseSummary final {
  public:
    const BaseIdentity& identity() const noexcept;
    const BaseHeaderFields& header() const noexcept;
    Crc32c prefix_crc() const noexcept;
    Crc32c done_crc() const noexcept;
    // Only generated bytes/metadata. NOT ValidatedBase, fsync or P2 completion.
  private:
    friend class BaseEncodingCursor;
    EncodedBaseSummary(BaseIdentity, BaseHeaderFields, Crc32c, Crc32c) noexcept;
    BaseIdentity identity_;
    BaseHeaderFields header_;
    Crc32c prefix_, done_;
};
// Pure byte producer. No filesystem/Database calls, root ownership or P2 proof.
// bytes() is invalidated by next/move/replacement/destruction; summary only at End.
class BaseEncodingCursor final {
  public:
    BaseEncodingCursor() noexcept;
    ~BaseEncodingCursor() noexcept;
    BaseEncodingCursor(const BaseEncodingCursor&) = delete;
    BaseEncodingCursor& operator=(const BaseEncodingCursor&) = delete;
    BaseEncodingCursor(BaseEncodingCursor&&) noexcept;
    BaseEncodingCursor& operator=(BaseEncodingCursor&&) noexcept;
    static BaseEncodingCursor begin(BaseEncodingContext, BaseInputView, BaseEncodeLimits) noexcept;
    BaseEncodeStep next() noexcept;
    ByteView bytes() const noexcept;
    bool complete() const noexcept;
    BaseEncodeFailure error() const noexcept;
    std::uint64_t bytes_emitted() const noexcept;
    const EncodedBaseSummary* result() const noexcept;

  private:
    enum class Phase { Empty, Header, Keys, Lru, Done, Complete, Failed, MovedFrom };
    // Proposed representation: no PImpl allocation, root/FD/child owner or callback.
    Phase phase_ = Phase::Empty;
    std::optional<BaseEncodingContext> context_;
    BaseInputView input_{};
    BaseEncodeLimits limits_{};
    BaseHeaderFields header_{};
    BaseHeader header_bytes_{};
    std::vector<std::byte> seen_; // bounded permutation metadata only
    std::string frame_;           // current KEY1/LRU1/DONE, never whole base
    std::size_t key_index_ = 0, lru_index_ = 0;
    std::uint64_t expected_extent_ = 0, emitted_ = 0;
    std::uint32_t prefix_ = 0, done_ = 0, file_crc_ = 0;
    bool chunk_live_ = false, header_chunk_ = false;
    BaseEncodeFailure failure_{};
    std::optional<EncodedBaseSummary> result_;
};
} // namespace redisdb::persistence::v2
